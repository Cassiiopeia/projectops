"""pro-launch `web script` 에 넘기는 렌더 스크립트 생성 (#1021)

`web shot` 은 webp 로 줄여 저장하므로 쓰지 않는다. Playwright 의 page.screenshot 은
뷰포트 그대로(예: 1320x2868) 알파 없는 PNG 로 저장한다 (실측).
"""
from __future__ import annotations

import json

from figma_tools.store_html import FIT_ATTRIBUTE

# 글꼴 로드 후 문구 상자가 넘치는지 / 모든 이미지가 실제로 읽혔는지
_FIT_CHECK_JS = (f"[...document.querySelectorAll('[{FIT_ATTRIBUTE}]')]"
                 ".some(e => e.scrollHeight > e.clientHeight + 1 || e.scrollWidth > e.clientWidth + 1)")
_IMAGES_LOADED_JS = "[...document.images].every(i => i.complete && i.naturalWidth > 0)"

_SCRIPT_TEMPLATE = '''\
# Generated by figma_cli store-compose (#1021). Run: launch_cli.py web script --file <this file>
# Renders every job in the manifest to an exact-size PNG. Use your own tab (LAUNCH_TAB=compose).
import json
import pathlib

jobs = json.loads(pathlib.Path({manifest_path}).read_text(encoding="utf-8"))["jobs"]
rendered, overflowed, failed = [], [], []
for job in jobs:
    try:
        page.set_viewport_size({{"width": job["width"], "height": job["height"]}})
        page.goto(job["html_uri"], wait_until="load")
        page.evaluate("document.fonts.ready")
        if not page.evaluate({images_loaded_js}):
            failed.append({{"id": job["id"], "reason": "image_not_loaded"}})
            continue
        if page.evaluate({fit_check_js}):
            overflowed.append(job["id"])
        out_path = pathlib.Path(job["image"])
        out_path.parent.mkdir(parents=True, exist_ok=True)
        page.screenshot(path=str(out_path), type="png")
        rendered.append(job["id"])
    except Exception as error:
        failed.append({{"id": job["id"], "reason": str(error)[:200]}})
result = {{"rendered": len(rendered), "text_overflow": overflowed, "failed": failed}}
'''


def build_render_script(manifest_path: str) -> str:
    """json.dumps 로 경로를 따옴표·이스케이프된 파이썬 문자열 리터럴로 넣는다"""
    return _SCRIPT_TEMPLATE.format(manifest_path=json.dumps(manifest_path),
                                   images_loaded_js=json.dumps(_IMAGES_LOADED_JS),
                                   fit_check_js=json.dumps(_FIT_CHECK_JS))

"""Argument contract for management commands: secrets are never accepted, only credential names"""
from . import manage, triggers


def register(sub):
    parser = sub.add_parser("manage", help="installation, harness wiring, ingestion, search and publication")
    parser.add_argument("action", choices=manage.HANDLERS)
    parser.add_argument("--repo")
    parser.add_argument("--gbrain-home")
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--yes", action="store_true")
    parser.add_argument("--probe", action="store_true")
    parser.add_argument("--engine", choices=("pglite", "postgres"), default="pglite")
    parser.add_argument("--harness", choices=("claude-code", "codex"))
    parser.add_argument("--capture", action="store_true")
    parser.add_argument("--no-hooks", action="store_true")
    parser.add_argument("--source")
    parser.add_argument("--query")
    parser.add_argument("--semantic", action="store_true")
    parser.add_argument("--embedding", action="store_true")
    parser.add_argument("--model")
    parser.add_argument("--dimensions", type=int)
    parser.add_argument("--credential")
    parser.add_argument("--credential-field")
    parser.add_argument("--credential-env")
    parser.add_argument("--file")
    parser.add_argument("--out")
    parser.add_argument("--content-sha")
    parser.add_argument("--issue", type=int)
    parser.add_argument("--schedule-action", choices=("status", "install", "pause", "resume"), default="status")
    parser.add_argument("--target", choices=("macos", "linux-systemd", "ephemeral-container", "linux-cron"))
    trigger = sub.add_parser("triggers", help="inspect or configure multiple capture events")
    trigger.add_argument("--repo")
    trigger.add_argument("--events")
    trigger.add_argument("--runner", choices=("agent", "existing-ci", "server"), default="agent")
    trigger.add_argument("--source")
    trigger.add_argument("--apply", action="store_true")
    trigger.add_argument("--yes", action="store_true")
    event = sub.add_parser("event", help="collect or deliver one knowledge record idempotently")
    event.add_argument("event", choices=triggers.EVENTS)
    event.add_argument("--repo")
    event.add_argument("--issue", type=int)
    event.add_argument("--record-id")
    event.add_argument("--note")
    event.add_argument("--outcome", choices=("success", "failure", "unknown"), default="unknown")
    event.add_argument("--apply", action="store_true")
    event.add_argument("--yes", action="store_true")
    return {"manage": manage.cmd_manage, "triggers": triggers.configure, "event": triggers.handle_event}
